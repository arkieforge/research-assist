// `vp run triage [what went wrong]`: start a coding agent on the triage playbook, like `npx t3 triage`.
// Collects machine and deploy facts into .t3/triage/context-<time>.md, then launches Claude Code or
// Codex in this terminal with .github/triage/PLAYBOOK.md and that file. Node built-ins only.
//
//   vp run triage "chat list is empty after sending"   start with a description
//   vp run triage --agent codex                        pick the agent (default: claude, then codex)
//   vp run triage --print                              print the prompt instead (paste it into a T3 thread)
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { devStage, preferredPorts, root, run, succeeds } from "./lib/local.ts";

const argv = process.argv.slice(2);
const flag = (name: string) => {
	const i = argv.indexOf(name);
	return i === -1 ? undefined : (argv.splice(i, 2)[1] ?? "");
};
const agentChoice = flag("--agent");
const printOnly = argv.includes("--print");
const description = argv
	.filter((a) => a !== "--print")
	.join(" ")
	.trim();

const output = (cmd: string, args: string[]) => {
	try {
		return run(cmd, args).trim();
	} catch {
		return "(unavailable)";
	}
};
const ghReady = succeeds("gh", ["auth", "status"]);
const now = new Date();

// Facts only; the playbook decides what to do with them. Nothing here may contain a secret value.
const context = `# Triage context (generated by vp run triage)

- Generated: ${now.toISOString()} (local timezone ${Intl.DateTimeFormat().resolvedOptions().timeZone})
- Machine: ${process.platform} ${process.arch}, node ${process.versions.node}, vp ${output("vp", ["--version"]).split("\n")[0]}
- Checkout: ${root}
- Local HEAD: ${output("git", ["log", "-1", "--format=%h %s (%cr)"])} on ${output("git", ["branch", "--show-current"]) || "detached HEAD"}
- origin/main: ${output("git", ["ls-remote", "origin", "refs/heads/main"]).split(/\s/)[0]?.slice(0, 7) || "(unknown)"}
- Local dev stage: ${devStage()}; preferred ports ${JSON.stringify(preferredPorts())}

## Recent prod API deploys (Deploy API workflow)

${ghReady ? output("gh", ["run", "list", "--workflow", "deploy-api.yml", "--limit", "5", "--json", "conclusion,headSha,createdAt,displayTitle", "--jq", '.[] | "- \\(.createdAt) \\(.conclusion // "running") \\(.headSha[0:7]) \\(.displayTitle)"']) || "(none)" : "(gh not logged in)"}

## Open incidents and recent triage reports

${ghReady ? output("gh", ["issue", "list", "--search", "label:incident,via-triage", "--state", "all", "--limit", "10", "--json", "number,title,state,labels", "--jq", '.[] | "- #\\(.number) [\\(.state)] \\(.title)"']) || "(none)" : "(gh not logged in)"}

## vp run doctor

\`\`\`
${spawnSync("node", ["scripts/doctor.ts"], { cwd: root, encoding: "utf8" }).stdout.trim()}
\`\`\`
`;

const dir = join(root, ".t3", "triage");
mkdirSync(dir, { recursive: true });
const file = join(dir, `context-${now.toISOString().replace(/[:.]/g, "-")}.md`);
writeFileSync(file, context);

const prompt = [
	"You are triaging a problem with Arkie. Read and follow .github/triage/PLAYBOOK.md",
	"(use the default branch's copy, as step 2 says).",
	`Machine and deploy facts are in ${relative(root, file)}; read it before investigating.`,
	description ? `The reporter says: ${description}` : "Start by asking what went wrong.",
].join(" ");

const agents = agentChoice ? [agentChoice] : ["claude", "codex"];
const agent = printOnly ? undefined : agents.find((name) => succeeds(name, ["--version"]));
if (!agent) {
	if (!printOnly) process.stdout.write(`No ${agents.join(" or ")} CLI found. Paste this into a T3 Code thread:\n\n`);
	process.stdout.write(`${prompt}\n`);
	process.exit(0);
}
process.stdout.write(`Context: ${relative(root, file)}\nStarting ${agent}...\n`);
process.exit(spawnSync(agent, [prompt], { cwd: root, stdio: "inherit" }).status ?? 1);
